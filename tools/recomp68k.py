"""satrecomp code generator for the sound CPU (MC68EC000): turns its block database into C++.

Input:  the sound CPU block database (written by the port with --record-blocks, next to the SH-2 one)
        the decode tables (written by the port with --dump-decode)
        Ymir's 68000 sources (for the opcode names and the handler each opcode maps to)
Output: <out>/m68k_NNN.cpp   one function per block, each instruction a call to its handler with a constant opcode
        <out>/m68k_index.cpp the table of all generated files

Generated files are derived from the game's sound driver: never commit them.
"""

import argparse
import os
import re
import sys


def parse_opcode_names(decode_hpp):
    text = open(decode_hpp).read()
    m = re.search(r"enum class OpcodeType\s*:\s*\w+\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("cannot find enum class OpcodeType in " + decode_hpp)
    names = []
    for line in m.group(1).split("\n"):
        line = line.split("//")[0].strip()
        for part in line.split(","):
            part = part.strip()
            if part:
                if "=" in part:
                    sys.exit("OpcodeType with explicit values is not supported: " + part)
                names.append(part)
    return names


def parse_handlers(m68k_cpp):
    """OpcodeType name -> C++ call text, from the interpreter's dispatch switch."""
    text = open(m68k_cpp).read()
    handlers = {}
    for m in re.finditer(r"case OpcodeType::(\w+):\s*return\s+(\w+)(<[^>]*>)?\(instr\);", text):
        name, fn, targs = m.groups()
        handlers[name] = fn + (targs or "") + "(0x%04X)"
    return handlers


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--blocks", required=True)
    ap.add_argument("--decode", required=True)
    ap.add_argument("--ymir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--per-file", type=int, default=600)
    args = ap.parse_args()

    core = os.path.join(args.ymir, "libs", "ymir-core")
    names = parse_opcode_names(os.path.join(core, "include", "ymir", "hw", "m68k", "m68k_decode.hpp"))
    handlers = parse_handlers(os.path.join(core, "src", "ymir", "hw", "m68k", "m68k.cpp"))
    raw = open(args.decode, "rb").read()
    if len(raw) != 6 * 0x10000:
        sys.exit("unexpected decode table size (rebuild the port and dump it again)")
    decode = raw[5 * 0x10000:]

    blocks = set()
    if os.path.exists(args.blocks):
        for line in open(args.blocks):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            instrs = tuple((int(o, 16), int(c, 16)) for o, c in (p.split(":") for p in parts[1:]))
            blocks.add((int(parts[0], 16), instrs))
    blocks = sorted(blocks)

    os.makedirs(args.out, exist_ok=True)
    files = []
    total = 0
    for start in range(0, len(blocks), args.per_file):
        index = len(files)
        out = ["// Generated by satrecomp/tools/recomp68k.py from the game's sound driver. Do not edit, do not commit.",
               "#define SATRECOMP_OPS_ONLY",
               "#include <ymir/hw/m68k/m68k.cpp>",
               "",
               '#include "m68k_blocks.h"',
               "",
               "namespace satrecomp {",
               "",
               "template <>",
               "struct M68KBlockSet<%d> {" % index]
        descs = []
        for address, instrs in blocks[start:start + args.per_file]:
            calls = []
            for offset, opcode in instrs:
                h = handlers.get(names[decode[opcode]])
                if h is None:
                    calls = None
                    break
                calls.append(h % opcode)
            if calls is None:
                continue
            ident = "m%06X_%d" % (address, len(descs))
            out.append("    static uint64_t %s(ymir::m68k::MC68EC000 &c, uint64_t budget) {" % ident)
            out.append("        SM_BEGIN()")
            for k, call in enumerate(calls):
                if k + 1 < len(calls):
                    out.append("        SM_OP(%d, %s)" % (instrs[k + 1][0], call))
                else:
                    out.append("        SM_LAST(%s)" % call)
            out.append("    }")
            descs.append((address, instrs, ident))
            total += len(instrs)
        out.append("};")
        out.append("")
        for address, instrs, ident in descs:
            out.append("static const M68KInstr instrs_%s[] = {%s};" % (
                ident, ",".join("{%d,0x%04X}" % i for i in instrs)))
        out.append("")
        out.append("extern const M68KBlockDesc g_m68kBlocks_%d[];" % index)
        out.append("const M68KBlockDesc g_m68kBlocks_%d[] = {" % index)
        for address, instrs, ident in descs:
            out.append("    {0x%06X, %d, instrs_%s, &M68KBlockSet<%d>::%s}," % (address, len(instrs), ident, index, ident))
        if not descs:
            out.append("    {0, 0, nullptr, nullptr},")
        out.append("};")
        out.append("extern const size_t g_m68kBlocks_%d_count;" % index)
        out.append("const size_t g_m68kBlocks_%d_count = %d;" % (index, len(descs)))
        out.append("")
        out.append("} // namespace satrecomp")
        files.append(("m68k_%03d.cpp" % index, "\n".join(out) + "\n"))

    idx = ["// Generated by satrecomp/tools/recomp68k.py. Do not edit, do not commit.",
           '#include "m68k_blocks.h"', "", "namespace satrecomp {", ""]
    for i in range(len(files)):
        idx.append("extern const M68KBlockDesc g_m68kBlocks_%d[];" % i)
        idx.append("extern const size_t g_m68kBlocks_%d_count;" % i)
    idx.append("")
    idx.append("const M68KBlockTable g_m68kBlockTables[] = {")
    for i in range(len(files)):
        idx.append("    {g_m68kBlocks_%d, g_m68kBlocks_%d_count}," % (i, i))
    if not files:
        idx.append("    {nullptr, 0},")
    idx.append("};")
    idx.append("const size_t g_m68kBlockTableCount = %d;" % len(files))
    idx.append("")
    idx.append("} // namespace satrecomp")
    files.append(("m68k_index.cpp", "\n".join(idx) + "\n"))

    wanted = set()
    written = 0
    for name, content in files:
        path = os.path.join(args.out, name)
        wanted.add(name)
        if os.path.exists(path) and open(path).read() == content:
            continue
        with open(path, "w") as f:
            f.write(content)
        written += 1
    for name in os.listdir(args.out):
        if name.startswith("m68k_") and name.endswith(".cpp") and name not in wanted:
            os.remove(os.path.join(args.out, name))
    print("recomp68k: %d blocks, %d instructions, %d files (%d written)" % (len(blocks), total, len(files) - 1, written))


if __name__ == "__main__":
    main()
